/// BLOSUM substitution matrices.
///
/// Raw lower-triangular data from the C `blosum.c`, unpacked into symmetric
/// 20x20 matrices. Amino acid order: ARNDCQEGHILKMFPSTWYVBZX.-J (standard 20).

/// Default amino acid frequencies for BLOSUM matrices.
pub fn blosum_frequencies() -> [f64; 20] {
    [
        0.077, 0.051, 0.043, 0.052, 0.020, 0.041, 0.062, 0.074, 0.023, 0.052,
        0.091, 0.059, 0.024, 0.040, 0.051, 0.069, 0.059, 0.014, 0.032, 0.066,
    ]
}

/// Get a BLOSUM matrix by number (30, 45, 50, 62, 80).
///
/// Returns the symmetric 20x20 matrix in integer form.
pub fn blosum_matrix(n: i32) -> [[f64; 20]; 20] {
    let lower_tri = match n {
        30 => &BLOSUM30[..],
        45 => &BLOSUM45[..],
        50 => &BLOSUM50[..],
        62 => &BLOSUM62[..],
        80 => &BLOSUM80[..],
        _ => &BLOSUM62[..], // default
    };
    unpack_lower_triangular(lower_tri)
}

/// Unpack a lower-triangular array into a symmetric 20x20 matrix.
fn unpack_lower_triangular(tri: &[f64]) -> [[f64; 20]; 20] {
    let mut mtx = [[0.0f64; 20]; 20];
    let mut k = 0;
    for i in 0..20 {
        for j in 0..=i {
            mtx[i][j] = tri[k];
            mtx[j][i] = tri[k];
            k += 1;
        }
    }
    mtx
}


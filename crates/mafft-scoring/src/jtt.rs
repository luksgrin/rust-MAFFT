/// Get the raw JTT matrix data (for validation against C).
pub fn jtt_matrix() -> [[f64; 20]; 20] {
    build_jtt_pam_matrix(false, 200)
}

fn identity_20() -> [[f64; 20]; 20] {
    let mut m = [[0.0f64; 20]; 20];
    for i in 0..20 { m[i][i] = 1.0; }
    m
}

fn mat_mul_20(a: &[[f64; 20]; 20], b: &[[f64; 20]; 20]) -> [[f64; 20]; 20] {
    let mut c = [[0.0f64; 20]; 20];
    for i in 0..20 {
        for k in 0..20 {
            let a_ik = a[i][k];
            if a_ik == 0.0 { continue; }
            for j in 0..20 {
                c[i][j] += a_ik * b[k][j];
            }
        }
    }
    c
}

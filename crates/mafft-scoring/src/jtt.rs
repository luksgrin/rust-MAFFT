/// Build a PAM matrix from the JTT (or TM) model.
///
/// - `is_tm`: if true, use transmembrane frequencies
/// - `pam_n`: number of PAM iterations (typically 200)
///
/// Returns a 20x20 log-transformed scoring matrix (before normalization).
pub fn build_jtt_pam_matrix(is_tm: bool, pam_n: usize) -> [[f64; 20]; 20] {
    let freq = if is_tm { tm_frequencies() } else { jtt_frequencies() };
    let rsr = jtt_rsr_matrix(&freq);

    // Build PAM1 from RSR
    let mut pam1 = [[0.0f64; 20]; 20];
    let mut mutability = [0.0f64; 20];
    for i in 0..20 {
        for j in 0..20 {
            mutability[i] += rsr[i][j] * freq[j];
        }
    }
    let total: f64 = (0..20).map(|i| mutability[i] * freq[i]).sum();
    let delta = 0.01 / total;
    for i in 0..20 {
        for j in 0..20 {
            if i != j {
                pam1[i][j] = delta * rsr[i][j] * freq[j];
            } else {
                pam1[i][j] = 1.0 - delta * mutability[i];
            }
        }
    }

    // Exponentiate: pamx = pam1^pam_n
    let mut pamx = identity_20();
    for _ in 0..pam_n {
        pamx = mat_mul_20(&pamx, &pam1);
    }

    // Divide by background frequency
    for i in 0..20 {
        for j in 0..20 {
            pamx[i][j] /= freq[j];
        }
    }

    // Log transform
    for i in 0..20 {
        for j in 0..20 {
            if pamx[i][j] <= 0.0 {
                pamx[i][j] = 0.00001; // avoid log(0)
            }
            pamx[i][j] = pamx[i][j].log10() * 1000.0;
        }
    }

    pamx
}


#!/usr/bin/env python3
"""Scaling corpus for the n = 100 ... 5000 wall-clock benchmark (issue #22).

Ten Pfam families (full-length UniProtKB sequences, not domain-trimmed)
plus one nucleotide set (RefSeq 16S rRNA), each deterministically
subsampled to nested sizes n = 100, 250, 500, 1000 (5000 for two
families, used only by the FFT-NS-2 and --parttree points; 2000 for the
16S set). `benchmarks/scaling.py` aligns them.

Sources
-------

Protein: UniProtKB REST (`rest.uniprot.org/uniprotkb/stream`), query

    xref:pfam-<PFAM> AND fragment:false AND length:[50 TO 3000]
      AND (reviewed:true OR existence:1)

i.e. every non-fragment entry with a Pfam match to the family that is
either Swiss-Prot or has protein-level evidence. Swiss-Prot alone has
fewer than 1000 members for half of the families and nowhere near 5000;
the evidence filter keeps the pool curated while making n = 5000
possible. The 3000-residue cap keeps single giant proteins (titin-like
kinases, ~35 000 aa) from dominating the cost of a whole subsample.

Nucleotide: NCBI nuccore, BioProject PRJNA33175 (RefSeq "16S ribosomal
RNA" targeted loci for Bacteria and Archaea), fetched with E-utilities.

Sampling
--------

The pool is deduplicated by accession and sorted; it is shuffled with
`random.Random("scaling:<set>")` and the first max(n) accessions are
kept. Every size is a prefix of the next (n = 100 is the first 100 of
n = 250, ...), in that shuffled order. FASTA names are bare accessions.

What is in git and what is not
------------------------------

* `benchmarks/corpus/manifest.tsv`: per set and n, the source, query,
  database release, download date, pool size and min / median / max /
  total sequence length.
* `benchmarks/corpus/accessions/<set>.txt`: the ordered accessions of
  the largest subsample (the smaller ones are its prefixes).
* `benchmarks/corpus/SHA256SUMS`: checksums of every subsample FASTA.
* The FASTA files themselves live under `target/scaling_corpus/`
  (`<set>/n<N>.fa`), regenerated by this script.

USAGE
-----

    # Rebuild the committed corpus: fetch exactly the committed accessions
    # and check the result against SHA256SUMS (a mismatch means UniProt or
    # NCBI updated a sequence since the corpus was drawn):
    benchmarks/scaling_corpus.py build

    # Draw a new corpus from the current database release (rewrites the
    # manifest, the accession lists and SHA256SUMS):
    benchmarks/scaling_corpus.py build --resample

    # Only some sets:
    benchmarks/scaling_corpus.py build --sets PF00069 16S

    # Check the FASTA files on disk against SHA256SUMS:
    benchmarks/scaling_corpus.py verify

Downloads are retried with backoff; the raw pools are cached under
`target/scaling_corpus/pool/`, so an interrupted run resumes.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import random
import statistics
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CORPUS_DIR = REPO / "benchmarks" / "corpus"
ACC_DIR = CORPUS_DIR / "accessions"
MANIFEST = CORPUS_DIR / "manifest.tsv"
SUMS = CORPUS_DIR / "SHA256SUMS"
DATA_DIR = REPO / "target" / "scaling_corpus"
POOL_DIR = DATA_DIR / "pool"

SIZES = (100, 250, 500, 1000)
# (set id, Pfam name, sizes)
PROTEIN_SETS = [
    ("PF00069", "Pkinase", SIZES + (5000,)),
    ("PF00005", "ABC_tran", SIZES + (5000,)),
    ("PF00400", "WD40", SIZES),
    ("PF00072", "Response_reg", SIZES),
    ("PF07690", "MFS_1", SIZES),
    ("PF00067", "p450", SIZES),
    ("PF00001", "7tm_1", SIZES),
    ("PF00528", "BPD_transp_1", SIZES),
    ("PF00106", "adh_short", SIZES),
    ("PF02518", "HATPase_c", SIZES),
]
NUC_SETS = [
    ("16S", "16S rRNA (RefSeq PRJNA33175)", SIZES + (2000,)),
]
ALL_SETS = [s[0] for s in PROTEIN_SETS + NUC_SETS]

UNIPROT_QUERY = ("xref:pfam-{pfam} AND fragment:false AND length:[50 TO 3000] "
                 "AND (reviewed:true OR existence:1)")
UNIPROT_STREAM = "https://rest.uniprot.org/uniprotkb/stream"
UNIPROT_ACCESSIONS = "https://rest.uniprot.org/uniprotkb/accessions"
NCBI_TERM = "33175[BioProject]"
EUTILS = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils"

MANIFEST_COLUMNS = ["set", "name", "molecule", "source", "query", "release",
                    "download_date", "n_available", "n", "min_len", "median_len",
                    "max_len", "total_len"]


# ------------------------------------------------------------------- network

def http(url: str, data: dict | None = None, tries: int = 6,
         timeout: int = 300) -> tuple[bytes, dict]:
    """GET (or POST form `data`) with exponential backoff; returns body, headers."""
    body = urllib.parse.urlencode(data).encode() if data is not None else None
    delay = 5.0
    for attempt in range(1, tries + 1):
        try:
            req = urllib.request.Request(url, data=body,
                                         headers={"User-Agent": "rust-MAFFT-bench"})
            with urllib.request.urlopen(req, timeout=timeout) as r:
                return r.read(), {k.lower(): v for k, v in r.headers.items()}
        except (urllib.error.URLError, TimeoutError, ConnectionError, OSError) as e:
            if attempt == tries:
                raise
            print(f"  {e}; retry {attempt}/{tries - 1} in {delay:.0f}s", file=sys.stderr)
            time.sleep(delay)
            delay = min(delay * 2, 120)
    raise AssertionError("unreachable")


# --------------------------------------------------------------------- FASTA

def parse_fasta(text: str) -> list[tuple[str, str]]:
    out: list[tuple[str, list[str]]] = []
    for line in text.splitlines():
        if line.startswith(">"):
            out.append((line[1:].strip(), []))
        elif out and line.strip():
            out[-1][1].append(line.strip())
    return [(h, "".join(s)) for h, s in out]


def uniprot_acc(header: str) -> str:
    # ">sp|P12345|NAME_HUMAN ..." / ">tr|A0A0...|..."
    tok = header.split()[0]
    parts = tok.split("|")
    return parts[1] if len(parts) >= 3 else tok


def write_fasta(records: list[tuple[str, str]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = []
    for name, seq in records:
        lines.append(f">{name}")
        lines += [seq[i:i + 60] for i in range(0, len(seq), 60)]
    path.write_text("\n".join(lines) + "\n")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


# --------------------------------------------------------------------- pools

def uniprot_pool(pfam: str) -> tuple[dict[str, str], dict]:
    """All pool sequences by accession, plus provenance; cached on disk."""
    fa = POOL_DIR / f"{pfam}.fasta"
    meta_p = POOL_DIR / f"{pfam}.json"
    if fa.is_file() and meta_p.is_file():
        meta = json.loads(meta_p.read_text())
    else:
        query = UNIPROT_QUERY.format(pfam=pfam)
        print(f"{pfam}: downloading pool ({query})", file=sys.stderr)
        url = f"{UNIPROT_STREAM}?" + urllib.parse.urlencode(
            {"query": query, "format": "fasta"})
        body, hdr = http(url)
        POOL_DIR.mkdir(parents=True, exist_ok=True)
        fa.write_bytes(body)
        meta = {"source": "UniProtKB", "query": query,
                "release": hdr.get("x-uniprot-release", "NA"),
                "download_date": dt.date.today().isoformat()}
        meta_p.write_text(json.dumps(meta))
    seqs: dict[str, str] = {}
    for h, s in parse_fasta(fa.read_text()):
        seqs.setdefault(uniprot_acc(h), s.upper())
    return seqs, meta


def uniprot_fetch(accs: list[str]) -> tuple[dict[str, str], str]:
    out: dict[str, str] = {}
    release = "NA"
    for i in range(0, len(accs), 200):
        batch = accs[i:i + 200]
        url = f"{UNIPROT_ACCESSIONS}?" + urllib.parse.urlencode(
            {"accessions": ",".join(batch), "format": "fasta", "size": 500})
        body, hdr = http(url)
        release = hdr.get("x-uniprot-release", release)
        for h, s in parse_fasta(body.decode()):
            out[uniprot_acc(h)] = s.upper()
    return out, release


def ncbi_ids() -> tuple[list[str], dict]:
    cache = POOL_DIR / "16S.ids.json"
    if cache.is_file():
        d = json.loads(cache.read_text())
        return d["ids"], d["meta"]
    print(f"16S: listing {NCBI_TERM}", file=sys.stderr)
    body, _ = http(f"{EUTILS}/esearch.fcgi?" + urllib.parse.urlencode(
        {"db": "nuccore", "term": NCBI_TERM, "retmax": 100000, "retmode": "json",
         "idtype": "acc"}))
    res = json.loads(body)["esearchresult"]
    ids = sorted(set(res["idlist"]))
    meta = {"source": "NCBI nuccore", "query": NCBI_TERM,
            "release": "NA", "download_date": dt.date.today().isoformat()}
    POOL_DIR.mkdir(parents=True, exist_ok=True)
    cache.write_text(json.dumps({"ids": ids, "meta": meta}))
    return ids, meta


def ncbi_fetch(accs: list[str]) -> dict[str, str]:
    cache = POOL_DIR / "16S.fetched.fasta"
    have: dict[str, str] = {}
    if cache.is_file():
        have = {h.split()[0]: s for h, s in parse_fasta(cache.read_text())}
    missing = [a for a in accs if a not in have]
    for i in range(0, len(missing), 200):
        batch = missing[i:i + 200]
        print(f"16S: efetch {i + len(batch)}/{len(missing)}", file=sys.stderr)
        body, _ = http(f"{EUTILS}/efetch.fcgi",
                       {"db": "nuccore", "id": ",".join(batch), "rettype": "fasta",
                        "retmode": "text"})
        got = {h.split()[0]: s.upper() for h, s in parse_fasta(body.decode())}
        have.update(got)
        with cache.open("a") as fh:
            for a, s in got.items():
                fh.write(f">{a}\n{s}\n")
        time.sleep(0.4)  # stay under NCBI's 3 requests/s without an API key
    return {a: have[a] for a in accs if a in have}


# ------------------------------------------------------------------ building

def shuffled(set_id: str, accs: list[str]) -> list[str]:
    accs = sorted(set(accs))
    random.Random(f"scaling:{set_id}").shuffle(accs)
    return accs


def length_stats(records: list[tuple[str, str]]) -> dict:
    lens = [len(s) for _, s in records]
    return {"min_len": min(lens), "median_len": int(statistics.median(lens)),
            "max_len": max(lens), "total_len": sum(lens)}


def build_set(set_id: str, name: str, molecule: str, sizes: tuple, resample: bool
              ) -> tuple[list[dict], dict[str, str]]:
    acc_file = ACC_DIR / f"{set_id}.txt"
    nmax = max(sizes)
    if resample or not acc_file.is_file():
        if molecule == "protein":
            pool, meta = uniprot_pool(set_id)
            order = shuffled(set_id, list(pool))
            n_avail = len(pool)
            chosen = order[:nmax]
            seqs = {a: pool[a] for a in chosen}
        else:
            ids, meta = ncbi_ids()
            n_avail = len(ids)
            chosen = shuffled(set_id, ids)[:nmax]
            seqs = ncbi_fetch(chosen)
            chosen = [a for a in chosen if a in seqs]
        ACC_DIR.mkdir(parents=True, exist_ok=True)
        acc_file.write_text("\n".join(chosen) + "\n")
    else:
        chosen = acc_file.read_text().split()
        old = {r["set"]: r for r in read_manifest()}.get(set_id, {})
        n_avail = int(old.get("n_available", 0) or 0)
        meta = {k: old.get(k, "NA") for k in ("source", "query", "release",
                                               "download_date")}
        if molecule == "protein":
            seqs, _ = uniprot_fetch(chosen)
        else:
            seqs = ncbi_fetch(chosen)
        lost = [a for a in chosen if a not in seqs]
        if lost:
            print(f"{set_id}: {len(lost)} accessions no longer resolvable "
                  f"(first: {lost[:5]})", file=sys.stderr)
        chosen = [a for a in chosen if a in seqs]

    rows, sums = [], {}
    for n in sizes:
        if n > len(chosen):
            print(f"{set_id}: only {len(chosen)} sequences, skipping n={n}",
                  file=sys.stderr)
            continue
        recs = [(a, seqs[a]) for a in chosen[:n]]
        path = DATA_DIR / set_id / f"n{n}.fa"
        write_fasta(recs, path)
        sums[f"{set_id}/n{n}.fa"] = sha256(path)
        rows.append({"set": set_id, "name": name, "molecule": molecule,
                     "source": meta["source"], "query": meta["query"],
                     "release": meta["release"], "download_date": meta["download_date"],
                     "n_available": n_avail, "n": n, **length_stats(recs)})
    return rows, sums


def read_manifest() -> list[dict]:
    if not MANIFEST.is_file():
        return []
    with MANIFEST.open() as fh:
        hdr = fh.readline().rstrip("\n").split("\t")
        return [dict(zip(hdr, l.rstrip("\n").split("\t"))) for l in fh if l.strip()]


def read_sums() -> dict[str, str]:
    if not SUMS.is_file():
        return {}
    out = {}
    for line in SUMS.read_text().splitlines():
        h, p = line.split(maxsplit=1)
        out[p.strip()] = h
    return out


def cmd_build(args) -> int:
    specs = {s[0]: (s[1], "protein", s[2]) for s in PROTEIN_SETS}
    specs.update({s[0]: (s[1], "nucleotide", s[2]) for s in NUC_SETS})
    old_rows = {(r["set"], r["n"]): r for r in read_manifest()}
    old_sums = read_sums()
    new_rows, new_sums = {}, {}
    for set_id in args.sets:
        name, mol, sizes = specs[set_id]
        rows, sums = build_set(set_id, name, mol, sizes, args.resample)
        for r in rows:
            new_rows[(r["set"], str(r["n"]))] = {k: str(v) for k, v in r.items()}
        new_sums.update(sums)

    if args.resample or not MANIFEST.is_file():
        rows = {k: v for k, v in old_rows.items() if k[0] not in args.sets}
        rows.update(new_rows)
        sums = {k: v for k, v in old_sums.items() if k.split("/")[0] not in args.sets}
        sums.update(new_sums)
        order = {s: i for i, s in enumerate(ALL_SETS)}
        CORPUS_DIR.mkdir(parents=True, exist_ok=True)
        with MANIFEST.open("w") as fh:
            fh.write("\t".join(MANIFEST_COLUMNS) + "\n")
            for k in sorted(rows, key=lambda k: (order.get(k[0], 99), int(k[1]))):
                fh.write("\t".join(rows[k][c] for c in MANIFEST_COLUMNS) + "\n")
        SUMS.write_text("".join(f"{sums[p]}  {p}\n" for p in
                                sorted(sums, key=lambda p: (order.get(p.split('/')[0], 99),
                                                            int(p.split('/n')[1][:-3])))))
        print(f"wrote {MANIFEST.relative_to(REPO)}, {SUMS.relative_to(REPO)}",
              file=sys.stderr)
        print(table(list(rows.values())))
        return 0
    bad = [p for p, h in new_sums.items() if old_sums.get(p) != h]
    for p in bad:
        print(f"checksum mismatch: {p}", file=sys.stderr)
    print(f"{len(new_sums) - len(bad)}/{len(new_sums)} files match SHA256SUMS",
          file=sys.stderr)
    return 1 if bad else 0


def cmd_verify(args) -> int:
    sums = read_sums()
    bad = 0
    for p, h in sums.items():
        f = DATA_DIR / p
        if not f.is_file():
            print(f"missing   {p}")
            bad += 1
        elif sha256(f) != h:
            print(f"MISMATCH  {p}")
            bad += 1
    print(f"{len(sums) - bad}/{len(sums)} OK")
    return 1 if bad else 0


def table(rows: list[dict]) -> str:
    """Markdown summary: one line per set, lengths of the largest subsample."""
    by_set: dict[str, list[dict]] = {}
    for r in rows:
        by_set.setdefault(r["set"], []).append(r)
    lines = ["| Set | Name | Molecule | Pool | Sizes | Length min / median / max (largest n) |",
             "|---|---|---|---:|---|---|"]
    for s in ALL_SETS:
        if s not in by_set:
            continue
        rs = sorted(by_set[s], key=lambda r: int(r["n"]))
        big = rs[-1]
        lines.append(f"| {s} | {big['name']} | {big['molecule']} | {big['n_available']} | "
                     f"{', '.join(r['n'] for r in rs)} | "
                     f"{big['min_len']} / {big['median_len']} / {big['max_len']} |")
    return "\n".join(lines)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.split("Sources")[0],
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="download and subsample")
    b.add_argument("--sets", nargs="+", default=ALL_SETS, choices=ALL_SETS)
    b.add_argument("--resample", action="store_true",
                   help="draw from the current database release instead of the "
                        "committed accession lists")
    b.set_defaults(func=cmd_build)
    v = sub.add_parser("verify", help="check target/scaling_corpus against SHA256SUMS")
    v.set_defaults(func=cmd_verify)
    t = sub.add_parser("table", help="Markdown summary of the manifest")
    t.set_defaults(func=lambda a: print(table(read_manifest())) or 0)
    args = p.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())

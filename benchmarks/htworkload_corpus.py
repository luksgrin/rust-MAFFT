#!/usr/bin/env python3
"""High-throughput workload corpus: thousands of small clusters (issue #23).

Two sets of real clusters of 2 ... 100 sequences, the shape of input a
pangenome or orthology pipeline feeds MAFFT one cluster at a time.
`benchmarks/htworkload.py` aligns them.

DNA: pangenome gene clusters (primary)
--------------------------------------

What panaroo / Roary hand to `mafft --auto --adjustdirection --thread 1
--nuc`: one FASTA per gene family, the family's CDS from every genome.

* Genomes: 30 RefSeq complete genomes of *Streptococcus pneumoniae*
  (taxid 1313), listed with the NCBI Datasets v2 REST API
  (`genome/taxon/1313/dataset_report`, `assembly_level=complete_genome`,
  `assembly_source=refseq`), sorted by accession, shuffled with
  `random.Random("htworkload:genomes")` and the first 30 kept.
* CDS: `genome/accession/<GCF>/download?include_annotation_type=CDS_FASTA`
  (`cds_from_genomic.fna`). Pseudogenes (`[pseudo=true]`), partial CDS
  (`[partial=...]`), CDS without a `protein_id` and CDS shorter than
  90 nt are dropped. Each CDS is named `g<genome index>_<ordinal>`, the
  ordinal being the `_<N>` suffix NCBI gives the CDS in that file (so
  the name is stable for a given annotation), e.g. `g07_1234`.
* Families: the CDS are translated (genetic code 11, frame 1, stop
  codons as `*` and trimmed at the end) and clustered with MMseqs2
  (`mmseqs easy-cluster --min-seq-id 0.7 -c 0.8 --cov-mode 0
  --cluster-mode 0 -s 7.5`), i.e. protein families at 70 % identity over
  80 % of both sequences, the family threshold panaroo uses (its
  `--family_threshold` default is 0.7). The DNA sequences of each family
  are what gets aligned, in the annotated (sense) orientation.
* Families with one member are dropped; families with more than 100
  members are subsampled to 100 with `random.Random("htworkload:<id>")`
  (the subsampled member list is what is committed). Cluster ids are
  `dna_00001` ... in order of their MMseqs2 representative's name.

Protein: orthogroups (secondary)
--------------------------------

OrthoDB v13 orthologous groups at the Saccharomycetaceae level (taxid
4893, 60 species), REST API `data.orthodb.org/v13/search?level=4893`
(paged with `skip`). Groups with 5 ... 60 genes are shuffled with
`random.Random("htworkload:orthogroups")` and the first 1500 kept; each
is fetched with `/v13/fasta?id=<og>`. Sequence names are the OrthoDB
gene ids (`4950_0:0011f2`); a trailing `*` is removed and `*` / `.`
inside a sequence become `X`. Cluster ids are the OrthoDB group ids.

What is in git and what is not
------------------------------

* `benchmarks/htworkload/manifest.tsv`: one row per cluster: id,
  molecule, n, n before the 100 cap, min / median / max length, SHA-256
  of the FASTA.
* `benchmarks/htworkload/clusters_dna.tsv`: the members of every DNA
  cluster (`<id>\\t<name>,<name>,...`).
* `benchmarks/htworkload/orthogroups.txt`: the OrthoDB group ids.
* `benchmarks/htworkload/provenance.json`: genome accessions and strains,
  MMseqs2 version and parameters, OrthoDB release, download dates.
* The FASTA files live under `target/htworkload_corpus/{dna,protein}/`,
  regenerated by this script; raw downloads are cached in
  `target/htworkload_corpus/pool/`.

USAGE
-----

    # Rebuild the committed corpus (downloads the 30 genomes and the
    # orthogroups, rebuilds every cluster from the committed member lists,
    # checks the SHA-256 column of the manifest). Needs no MMseqs2.
    benchmarks/htworkload_corpus.py build

    # Only one molecule
    benchmarks/htworkload_corpus.py build --molecule dna

    # Draw a new corpus from the current releases (needs `mmseqs` on PATH;
    # rewrites the committed files)
    benchmarks/htworkload_corpus.py build --resample

    benchmarks/htworkload_corpus.py verify     # FASTA on disk vs manifest
    benchmarks/htworkload_corpus.py table      # size distribution
"""

from __future__ import annotations

import argparse
import concurrent.futures as cf
import datetime as dt
import hashlib
import io
import json
import random
import re
import shutil
import statistics
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.parse
import urllib.request
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
META_DIR = REPO / "benchmarks" / "htworkload"
MANIFEST = META_DIR / "manifest.tsv"
CLUSTERS_DNA = META_DIR / "clusters_dna.tsv"
ORTHOGROUPS = META_DIR / "orthogroups.txt"
PROVENANCE = META_DIR / "provenance.json"
DATA_DIR = REPO / "target" / "htworkload_corpus"
POOL_DIR = DATA_DIR / "pool"

TAXON = 1313  # Streptococcus pneumoniae
N_GENOMES = 30
MIN_CDS_NT = 90
MAX_N = 100
MMSEQS_ARGS = ["--min-seq-id", "0.7", "-c", "0.8", "--cov-mode", "0",
               "--cluster-mode", "0", "-s", "7.5"]
DATASETS = "https://api.ncbi.nlm.nih.gov/datasets/v2"

ORTHODB = "https://data.orthodb.org/v13"
ORTHODB_LEVEL = 4893  # Saccharomycetaceae
OG_MIN, OG_MAX, N_OGS = 5, 60, 1500

MANIFEST_COLUMNS = ["cluster", "molecule", "n", "n_raw", "min_len", "median_len",
                    "max_len", "sha256"]
MOLECULES = ("dna", "protein")

# Genetic code 11 (= standard code for sense codons), TCAG order.
_B = "TCAG"
_AA = "FFLLSSSSYY**CC*WLLLLPPPPHHQQRRRRIIIMTTTTNNKKSSRRVVVVAAAADDEEGGGG"
CODONS = {a + b + c: _AA[16 * i + 4 * j + k]
          for i, a in enumerate(_B) for j, b in enumerate(_B) for k, c in enumerate(_B)}


# ------------------------------------------------------------------- network

def http(url: str, tries: int = 8, timeout: int = 300) -> bytes:
    delay = 5.0
    for attempt in range(1, tries + 1):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "rust-MAFFT-bench"})
            with urllib.request.urlopen(req, timeout=timeout) as r:
                return r.read()
        except (urllib.error.URLError, TimeoutError, ConnectionError, OSError) as e:
            if attempt == tries:
                raise
            print(f"  {url[:90]}: {e}; retry {attempt}/{tries - 1} in {delay:.0f}s",
                  file=sys.stderr)
            time.sleep(delay)
            delay = min(delay * 2, 120)
    raise AssertionError("unreachable")


# --------------------------------------------------------------------- FASTA

def parse_fasta(text: str) -> list[tuple[str, str]]:
    out: list[tuple[str, list[str]]] = []
    for line in text.splitlines():
        if line.startswith(">"):
            out.append((line[1:].strip(), []))
        elif out and line.strip():
            out[-1][1].append(line.strip())
    return [(h, "".join(s)) for h, s in out]


def fasta_text(records: list[tuple[str, str]]) -> str:
    lines = []
    for name, seq in records:
        lines.append(f">{name}")
        lines += [seq[i:i + 60] for i in range(0, len(seq), 60)]
    return "\n".join(lines) + "\n"


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def translate(nt: str) -> str:
    aa = "".join(CODONS.get(nt[i:i + 3], "X") for i in range(0, len(nt) - 2, 3))
    return aa.rstrip("*")


# ----------------------------------------------------------------------- DNA

def list_genomes() -> list[dict]:
    reports, token = [], None
    while True:
        q = {"filters.assembly_level": "complete_genome",
             "filters.assembly_source": "refseq", "page_size": 1000}
        if token:
            q["page_token"] = token
        d = json.loads(http(f"{DATASETS}/genome/taxon/{TAXON}/dataset_report?"
                            + urllib.parse.urlencode(q)))
        reports += d.get("reports", [])
        token = d.get("next_page_token")
        if not token:
            return reports


def genome_cds(acc: str) -> str:
    """cds_from_genomic.fna of one assembly, cached."""
    path = POOL_DIR / "genomes" / f"{acc}.cds.fna"
    if path.is_file():
        return path.read_text()
    print(f"  {acc}: downloading CDS", file=sys.stderr)
    for attempt in range(4):
        body = http(f"{DATASETS}/genome/accession/{acc}/download?"
                    "include_annotation_type=CDS_FASTA")
        try:
            with zipfile.ZipFile(io.BytesIO(body)) as z:
                name = next(n for n in z.namelist() if n.endswith("cds_from_genomic.fna"))
                text = z.read(name).decode()
            break
        except (zipfile.BadZipFile, StopIteration):
            print(f"  {acc}: bad archive, retrying", file=sys.stderr)
            time.sleep(10)
    else:
        raise RuntimeError(f"{acc}: no cds_from_genomic.fna")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return text


ORDINAL = re.compile(r"_(\d+)$")


def genome_records(idx: int, acc: str) -> dict[str, str]:
    """Filtered CDS of genome `idx`, by name `g<idx>_<ordinal>`."""
    out = {}
    for h, s in parse_fasta(genome_cds(acc)):
        if "[pseudo=true]" in h or "[partial=" in h or "[protein_id=" not in h:
            continue
        s = s.upper()
        if len(s) < MIN_CDS_NT:
            continue
        m = ORDINAL.search(h.split()[0])
        out[f"g{idx:02d}_{int(m.group(1)):04d}"] = s
    return out


def dna_resample(prov: dict) -> tuple[dict[str, list[str]], dict[str, int], dict[str, str]]:
    reports = list_genomes()
    by_acc = {r["accession"]: r for r in reports}
    accs = sorted(by_acc)
    random.Random("htworkload:genomes").shuffle(accs)
    chosen = accs[:N_GENOMES]
    prov["dna"] = {
        "source": f"NCBI Datasets v2, taxon {TAXON} (Streptococcus pneumoniae), "
                  "RefSeq complete genomes, CDS_FASTA",
        "n_available": len(accs), "download_date": dt.date.today().isoformat(),
        "genomes": [{"index": i, "accession": a,
                     "strain": (by_acc[a]["organism"].get("infraspecific_names") or {})
                     .get("strain", "NA"),
                     "annotation_date": by_acc[a].get("annotation_info", {})
                     .get("release_date", "NA")}
                    for i, a in enumerate(chosen)],
        "filters": f"no pseudo, no partial, has protein_id, >= {MIN_CDS_NT} nt",
        "clustering": "mmseqs easy-cluster " + " ".join(MMSEQS_ARGS)
                      + " on the translated CDS (code 11)",
        "max_n": MAX_N,
    }
    seqs: dict[str, str] = {}
    for i, a in enumerate(chosen):
        seqs.update(genome_records(i, a))
    mmseqs = shutil.which("mmseqs")
    if not mmseqs:
        sys.exit("error: --resample needs mmseqs on PATH (brew install mmseqs2)")
    prov["dna"]["mmseqs_version"] = subprocess.run(
        [mmseqs, "version"], capture_output=True, text=True).stdout.strip()
    with tempfile.TemporaryDirectory() as tmp:
        t = Path(tmp)
        (t / "prot.fa").write_text(fasta_text([(k, translate(v)) for k, v in seqs.items()]))
        subprocess.run(["nice", "-n", "19", mmseqs, "easy-cluster", str(t / "prot.fa"),
                        str(t / "res"), str(t / "work"), *MMSEQS_ARGS,
                        "--threads", "4", "-v", "1"], check=True)
        fam: dict[str, list[str]] = {}
        for line in (t / "res_cluster.tsv").read_text().splitlines():
            rep, mem = line.split("\t")
            fam.setdefault(rep, []).append(mem)
    clusters, n_raw = {}, {}
    fams = sorted((rep, sorted(m)) for rep, m in fam.items() if len(m) >= 2)
    for k, (rep, members) in enumerate(fams, 1):
        cid = f"dna_{k:05d}"
        n_raw[cid] = len(members)
        if len(members) > MAX_N:
            members = sorted(random.Random(f"htworkload:{cid}").sample(members, MAX_N))
        clusters[cid] = members
    prov["dna"]["n_families"] = len(fam)
    prov["dna"]["n_singletons"] = sum(1 for m in fam.values() if len(m) == 1)
    prov["dna"]["n_cds"] = len(seqs)
    return clusters, n_raw, seqs


def dna_build(resample: bool, prov: dict) -> tuple[list[dict], dict[str, str]]:
    if resample or not CLUSTERS_DNA.is_file():
        clusters, n_raw, seqs = dna_resample(prov)
        CLUSTERS_DNA.write_text("".join(f"{c}\t{','.join(m)}\n" for c, m in clusters.items()))
    else:
        clusters = {}
        for line in CLUSTERS_DNA.read_text().splitlines():
            c, m = line.split("\t")
            clusters[c] = m.split(",")
        old = {r["cluster"]: r for r in read_manifest()}
        n_raw = {c: int(old[c]["n_raw"]) if c in old else len(m) for c, m in clusters.items()}
        seqs = {}
        for g in prov["dna"]["genomes"]:
            seqs.update(genome_records(g["index"], g["accession"]))
    rows, texts = [], {}
    for c, members in clusters.items():
        missing = [m for m in members if m not in seqs]
        if missing:
            print(f"{c}: {len(missing)} members not in the annotation "
                  f"(first: {missing[:3]})", file=sys.stderr)
        recs = [(m, seqs[m]) for m in members if m in seqs]
        texts[c] = fasta_text(recs)
        rows.append(row(c, "dna", recs, n_raw[c], texts[c]))
    return rows, texts


# ------------------------------------------------------------------- protein

def orthodb_groups() -> list[dict]:
    cache = POOL_DIR / f"orthodb_{ORTHODB_LEVEL}.json"
    if cache.is_file():
        return json.loads(cache.read_text())
    out, skip = [], 0
    while True:
        d = json.loads(http(f"{ORTHODB}/search?" + urllib.parse.urlencode(
            {"level": ORTHODB_LEVEL, "limit": 100, "skip": skip})))
        page = d.get("bigdata") or []
        out += [{"id": g["id"], "gene_count": int(g["gene_count"]),
                 "present_in": int(g["present_in"]), "name": g["name"]} for g in page]
        print(f"  OrthoDB: {len(out)}/{d['count']} groups listed", file=sys.stderr)
        skip += 100
        if not page or skip >= int(d["count"]):
            break
    cache.parent.mkdir(parents=True, exist_ok=True)
    cache.write_text(json.dumps(out))
    return out


def og_fasta(og: str) -> list[tuple[str, str]]:
    path = POOL_DIR / "orthodb" / f"{og}.fa"
    if not path.is_file():
        body = http(f"{ORTHODB}/fasta?id={urllib.parse.quote(og)}").decode()
        if not body.startswith(">"):
            raise RuntimeError(f"{og}: unexpected response {body[:100]!r}")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
    recs = []
    for h, s in parse_fasta(path.read_text()):
        s = re.sub(r"[*.]", "X", s.upper().rstrip("*"))
        recs.append((h.split()[0], s))
    return recs


def protein_build(resample: bool, prov: dict) -> tuple[list[dict], dict[str, str]]:
    if resample or not ORTHOGROUPS.is_file():
        groups = orthodb_groups()
        pool = sorted(g["id"] for g in groups if OG_MIN <= g["gene_count"] <= OG_MAX)
        random.Random("htworkload:orthogroups").shuffle(pool)
        ogs = pool[:N_OGS]
        ORTHOGROUPS.write_text("\n".join(ogs) + "\n")
        prov["protein"] = {
            "source": f"OrthoDB v13, level {ORTHODB_LEVEL} (Saccharomycetaceae)",
            "api": ORTHODB, "n_groups_at_level": len(groups),
            "n_available": len(pool), "gene_count_range": [OG_MIN, OG_MAX],
            "download_date": dt.date.today().isoformat()}
    else:
        ogs = ORTHOGROUPS.read_text().split()
    with cf.ThreadPoolExecutor(4) as ex:
        fetched = dict(zip(ogs, ex.map(og_fasta, ogs)))
    rows, texts = [], {}
    for og in ogs:
        recs = fetched[og]
        texts[og] = fasta_text(recs)
        rows.append(row(og, "protein", recs, len(recs), texts[og]))
    return rows, texts


# ------------------------------------------------------------------ building

def row(cid: str, mol: str, recs: list[tuple[str, str]], n_raw: int, text: str) -> dict:
    lens = [len(s) for _, s in recs]
    return {"cluster": cid, "molecule": mol, "n": len(recs), "n_raw": n_raw,
            "min_len": min(lens), "median_len": int(statistics.median(lens)),
            "max_len": max(lens), "sha256": sha256_text(text)}


def read_manifest() -> list[dict]:
    if not MANIFEST.is_file():
        return []
    with MANIFEST.open() as fh:
        hdr = fh.readline().rstrip("\n").split("\t")
        return [dict(zip(hdr, l.rstrip("\n").split("\t"))) for l in fh if l.strip()]


def fasta_path(cluster: str, molecule: str) -> Path:
    return DATA_DIR / molecule / f"{cluster}.fa"


def cmd_build(args) -> int:
    META_DIR.mkdir(parents=True, exist_ok=True)
    prov = json.loads(PROVENANCE.read_text()) if PROVENANCE.is_file() else {}
    old = {r["cluster"]: r for r in read_manifest()}
    rows: dict[str, dict] = dict(old)
    changed = False
    bad = 0
    for mol in args.molecule:
        print(f"{mol}: building", file=sys.stderr)
        new_rows, texts = (dna_build if mol == "dna" else protein_build)(args.resample, prov)
        d = DATA_DIR / mol
        if d.is_dir():
            shutil.rmtree(d)
        d.mkdir(parents=True)
        for c, t in texts.items():
            fasta_path(c, mol).write_text(t)
        fresh = args.resample or not any(r["molecule"] == mol for r in old.values())
        if fresh:
            changed = True
            rows = {c: r for c, r in rows.items() if r["molecule"] != mol}
            rows.update({r["cluster"]: {k: str(v) for k, v in r.items()} for r in new_rows})
        else:
            for r in new_rows:
                if old.get(r["cluster"], {}).get("sha256") != r["sha256"]:
                    print(f"checksum mismatch: {mol}/{r['cluster']}", file=sys.stderr)
                    bad += 1
        print(f"{mol}: {len(new_rows)} clusters in {d.relative_to(REPO)}", file=sys.stderr)
    if changed:
        PROVENANCE.write_text(json.dumps(prov, indent=1) + "\n")
        with MANIFEST.open("w") as fh:
            fh.write("\t".join(MANIFEST_COLUMNS) + "\n")
            for r in sorted(rows.values(),
                            key=lambda r: (MOLECULES.index(r["molecule"]), r["cluster"])):
                fh.write("\t".join(str(r[c]) for c in MANIFEST_COLUMNS) + "\n")
        print(f"wrote {MANIFEST.relative_to(REPO)}", file=sys.stderr)
    print(table(list(rows.values())))
    if bad:
        print(f"{bad} clusters differ from the manifest (the annotation or OrthoDB "
              "changed since the corpus was drawn)", file=sys.stderr)
    return 1 if bad else 0


def cmd_verify(args) -> int:
    rows = read_manifest()
    bad = 0
    for r in rows:
        p = fasta_path(r["cluster"], r["molecule"])
        if not p.is_file():
            print(f"missing   {r['molecule']}/{r['cluster']}")
            bad += 1
        elif sha256_text(p.read_text()) != r["sha256"]:
            print(f"MISMATCH  {r['molecule']}/{r['cluster']}")
            bad += 1
    print(f"{len(rows) - bad}/{len(rows)} OK")
    return 1 if bad else 0


def table(rows: list[dict]) -> str:
    lines = ["| Set | Clusters | Sequences | n min / median / mean / max | n = 2–9 / 10–49 / "
             "50–100 | capped at 100 | Length (median of cluster medians) | Residues |",
             "|---|---:|---:|---|---|---:|---:|---:|"]
    for mol in MOLECULES:
        rs = [r for r in rows if r["molecule"] == mol]
        if not rs:
            continue
        ns = [int(r["n"]) for r in rs]
        meds = [int(r["median_len"]) for r in rs]
        bins = (sum(n < 10 for n in ns), sum(10 <= n < 50 for n in ns),
                sum(n >= 50 for n in ns))
        capped = sum(int(r["n_raw"]) > int(r["n"]) for r in rs)
        residues = sum(int(r["n"]) * int(r["median_len"]) for r in rs)
        lines.append(f"| {mol} | {len(rs)} | {sum(ns)} | {min(ns)} / "
                     f"{statistics.median(ns):g} / {statistics.mean(ns):.1f} / {max(ns)} | "
                     f"{bins[0]} / {bins[1]} / {bins[2]} | {capped} | "
                     f"{statistics.median(meds):g} | ~{residues / 1e6:.1f} M |")
    return "\n".join(lines)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.split("DNA:")[0],
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="download and assemble the clusters")
    b.add_argument("--molecule", nargs="+", default=list(MOLECULES), choices=MOLECULES)
    b.add_argument("--resample", action="store_true",
                   help="draw a new corpus from the current releases (needs mmseqs)")
    b.set_defaults(func=cmd_build)
    v = sub.add_parser("verify", help="check the FASTA files against the manifest")
    v.set_defaults(func=cmd_verify)
    t = sub.add_parser("table", help="Markdown summary of the manifest")
    t.set_defaults(func=lambda a: print(table(read_manifest())) or 0)
    args = p.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
